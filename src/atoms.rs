//! The ATOMS: what cannot be recomputed, as Turtle files under the host's state root, reached
//! through `urn:file:` (ikigai-fs). Each atom is one file, so each is its own golden thread:
//! a write through the kernel cuts exactly that file's readers.
//!
//! ```text
//! model/{q}/{classifier}/{digest}.ttl      a model verdict, written once (the judge)
//! model/{q}/last/{item}.ttl                the item's last digest the judge judged
//! model/{q}/spent/{source}/{date}.ttl      model calls spent that day
//! model/{q}/reserved/{classifier}/{digest}.ttl  a model call reserved before asking
//! model/{q}/reserved/{classifier}/{digest}.failed.ttl   how that call failed, if it did
//! model/{q}/reserved/{classifier}/{digest}.cleared.ttl  the curators' clears, appended
//! person/{principal}/{q}/{digest}.ttl      a person's latest correction (their corridor)
//! person/{principal}/{q}/last/{item}.ttl   the item's last digest that person corrected
//! ```
//!
//! `{item}` and `{principal}` are the bare-hex digests of the item's and the principal's IRIs,
//! so an IRI of any spelling is one path segment. The split is the path ACL: the judge's
//! caller holds `urn:cap:fs:write:/model`, a reviewer `urn:cap:fs:write:/person/{principal}`.

use ikigai_core::{Error, Result};
use oxrdf::{NamedOrBlankNode, Term};

use crate::digest_hex;

pub const PREFIXES: &str = "@prefix oa: <http://www.w3.org/ns/oa#> .\n\
@prefix prov: <http://www.w3.org/ns/prov#> .\n\
@prefix dcterms: <http://purl.org/dc/terms/> .\n\
@prefix schema: <https://schema.org/> .\n\
@prefix skos: <http://www.w3.org/2004/02/skos/core#> .\n\
@prefix xsd: <http://www.w3.org/2001/XMLSchema#> .\n\n";

const OA: &str = "http://www.w3.org/ns/oa#";
const DCTERMS: &str = "http://purl.org/dc/terms/";
const SCHEMA: &str = "https://schema.org/";
const PROV: &str = "http://www.w3.org/ns/prov#";
const JUDGE: &str = "urn:iki:judge:vocab:";

// --- paths --------------------------------------------------------------------------------

pub fn model_path(q: &str, classifier: &str, digest: &str) -> String {
    format!("urn:file:model/{q}/{classifier}/{digest}.ttl")
}

pub fn reservation_path(q: &str, classifier: &str, digest: &str) -> String {
    format!("urn:file:model/{q}/reserved/{classifier}/{digest}.ttl")
}

pub fn failure_path(q: &str, classifier: &str, digest: &str) -> String {
    format!("urn:file:model/{q}/reserved/{classifier}/{digest}.failed.ttl")
}

pub fn cleared_path(q: &str, classifier: &str, digest: &str) -> String {
    format!("urn:file:model/{q}/reserved/{classifier}/{digest}.cleared.ttl")
}

pub fn model_last_path(q: &str, item: &str) -> String {
    format!(
        "urn:file:model/{q}/last/{}.ttl",
        digest_hex(item.as_bytes())
    )
}

pub fn spent_path(q: &str, source: &str, date: &str) -> String {
    format!("urn:file:model/{q}/spent/{source}/{date}.ttl")
}

pub fn principal_key(principal: &str) -> String {
    digest_hex(principal.as_bytes())
}

pub fn person_path(principal: &str, q: &str, digest: &str) -> String {
    format!(
        "urn:file:person/{}/{q}/{digest}.ttl",
        principal_key(principal)
    )
}

pub fn person_last_path(principal: &str, q: &str, item: &str) -> String {
    format!(
        "urn:file:person/{}/{q}/last/{}.ttl",
        principal_key(principal),
        digest_hex(item.as_bytes())
    )
}

// --- the atoms ----------------------------------------------------------------------------

/// A verdict as stored: a model's or a person's.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Stored {
    /// The label concept, or `None` for an unparsed model answer.
    pub concept: Option<String>,
    /// The raw answer an unparsed verdict keeps.
    pub raw: Option<String>,
    /// `dcterms:created`.
    pub created: String,
    /// `dcterms:creator` (a person) or `prov:wasAssociatedWith` (a model).
    pub agent: String,
}

pub struct ModelRecord<'a> {
    pub name: &'a str,
    pub target: &'a str,
    pub concept: Option<&'a str>,
    pub raw: Option<&'a str>,
    pub digest: &'a str,
    pub created: &'a str,
    pub endpoint: &'a str,
    pub model: &'a str,
    pub prompt: &'a str,
    pub prompt_digest: &'a str,
}

/// A model verdict: an `oa:Annotation` motivated by `oa:classifying`, its body the label
/// concept (or, unparsed, the raw answer as `oa:bodyValue`), generated by a run associated
/// with the provider endpoint, which records the model id and the prompt digest.
pub fn model_turtle(r: &ModelRecord<'_>) -> String {
    let run = format!("{}:run", r.name);
    let body = match (r.concept, r.raw) {
        (Some(c), _) => format!("oa:hasBody <{c}>"),
        (None, raw) => format!("oa:bodyValue \"{}\"", escape(raw.unwrap_or(""))),
    };
    format!(
        "{PREFIXES}<{name}> a oa:Annotation ;\n  oa:motivatedBy oa:classifying ;\n  \
         oa:hasTarget <{target}> ;\n  {body} ;\n  dcterms:identifier \"b3:{digest}\" ;\n  \
         dcterms:created \"{created}\"^^xsd:dateTime ;\n  \
         prov:wasAssociatedWith <{endpoint}> ;\n  prov:wasGeneratedBy <{run}> .\n\n\
         <{run}> a prov:Activity ;\n  prov:wasAssociatedWith <{endpoint}> ;\n  \
         prov:used <{prompt}> ;\n  schema:instrument \"{model}\" ;\n  \
         schema:version \"b3:{prompt_digest}\" .\n",
        name = r.name,
        target = r.target,
        digest = r.digest,
        created = r.created,
        endpoint = r.endpoint,
        prompt = r.prompt,
        model = escape(r.model),
        prompt_digest = r.prompt_digest,
    )
}

/// A person verdict: the same annotation shape, its creator the principal.
pub fn person_turtle(
    name: &str,
    target: &str,
    concept: &str,
    digest: &str,
    created: &str,
    principal: &str,
) -> String {
    format!(
        "{PREFIXES}<{name}> a oa:Annotation ;\n  oa:motivatedBy oa:classifying ;\n  \
         oa:hasTarget <{target}> ;\n  oa:hasBody <{concept}> ;\n  \
         dcterms:identifier \"b3:{digest}\" ;\n  \
         dcterms:created \"{created}\"^^xsd:dateTime ;\n  dcterms:creator <{principal}> .\n"
    )
}

/// The item's last judged (or corrected) digest.
pub fn last_turtle(name: &str, item: &str, digest: &str) -> String {
    format!(
        "{PREFIXES}<{name}> dcterms:subject <{item}> ;\n  dcterms:identifier \"b3:{digest}\" .\n"
    )
}

/// A durable attempt marker, kept even if the model call or its verdict write fails.
/// It is not a verdict: an uncertain outcome must never become an invented label. `attempt`
/// counts the calls reserved for the item, so a failure names the attempt it ended; a
/// curator's clear rewrites it with who cleared it and when.
pub fn reservation_turtle(
    name: &str,
    verdict: &str,
    created: &str,
    attempt: u32,
    cleared: Option<(&str, &str)>,
) -> String {
    let mut out = format!(
        "{PREFIXES}<{name}> a prov:Activity ;\n  dcterms:subject <{verdict}> ;\n  \
         dcterms:created \"{created}\"^^xsd:dateTime ;\n  \
         schema:position \"{attempt}\"^^xsd:integer"
    );
    if let Some((by, at)) = cleared {
        out.push_str(&format!(
            " ;\n  <{JUDGE}clearedBy> <{by}> ;\n  <{JUDGE}clearedAt> \"{at}\"^^xsd:dateTime"
        ));
    }
    out.push_str(" .\n");
    out
}

/// A reservation as stored.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Reservation {
    pub created: String,
    /// 1 for a reservation written before attempts were counted.
    pub attempt: u32,
    /// `(principal, time)` of a curator's clear.
    pub cleared: Option<(String, String)>,
}

/// How a reserved model call failed. `charged` is `yes` when the model answered (so the
/// provider billed the call) and `unknown` when the call itself failed.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Failure {
    pub attempt: u32,
    pub created: String,
    pub classifier: String,
    pub kind: String,
    pub message: String,
    pub charged: String,
    pub retry_at: String,
}

pub fn failure_turtle(name: &str, reservation: &str, f: &Failure) -> String {
    format!(
        "{PREFIXES}<{name}> a prov:Activity ;\n  dcterms:subject <{reservation}> ;\n  \
         schema:position \"{attempt}\"^^xsd:integer ;\n  \
         dcterms:created \"{created}\"^^xsd:dateTime ;\n  \
         schema:identifier \"{classifier}\" ;\n  schema:error \"{kind}\" ;\n  \
         schema:description \"{message}\" ;\n  <{JUDGE}charged> \"{charged}\" ;\n  \
         <{JUDGE}retryAt> \"{retry_at}\"^^xsd:dateTime .\n",
        attempt = f.attempt,
        created = f.created,
        classifier = f.classifier,
        kind = escape(&f.kind),
        message = escape(&f.message),
        charged = f.charged,
        retry_at = f.retry_at,
    )
}

/// One curator's clear, appended to the item's log: who, when, the attempt it cleared and
/// the failure it cleared, if one was recorded.
pub fn cleared_turtle(
    name: &str,
    reservation: &str,
    by: &str,
    at: &str,
    attempt: u32,
    failure: Option<&Failure>,
) -> String {
    let mut out = format!(
        "{PREFIXES}<{name}> a prov:Activity ;\n  dcterms:subject <{reservation}> ;\n  \
         dcterms:creator <{by}> ;\n  dcterms:created \"{at}\"^^xsd:dateTime ;\n  \
         schema:position \"{attempt}\"^^xsd:integer"
    );
    if let Some(f) = failure {
        out.push_str(&format!(
            " ;\n  schema:error \"{}\" ;\n  schema:description \"{}\"",
            escape(&f.kind),
            escape(&f.message)
        ));
    }
    out.push_str(" .\n");
    out
}

/// Model calls spent.
pub fn spent_turtle(name: &str, calls: u32) -> String {
    format!(
        "{PREFIXES}<{name}> a schema:QuantitativeValue ;\n  schema:value \"{calls}\"^^xsd:integer .\n"
    )
}

// --- reading them back --------------------------------------------------------------------

fn triples(text: &str) -> Result<Vec<(String, String, Term)>> {
    let mut out = Vec::new();
    for triple in oxttl::TurtleParser::new().for_slice(text.as_bytes()) {
        let t =
            triple.map_err(|e| Error::Endpoint(format!("a stored atom does not parse: {e}")))?;
        let subject = match t.subject {
            NamedOrBlankNode::NamedNode(n) => n.into_string(),
            other => other.to_string(),
        };
        out.push((subject, t.predicate.into_string(), t.object));
    }
    Ok(out)
}

fn object<'a>(
    ts: &'a [(String, String, Term)],
    subject: &str,
    predicate: &str,
) -> Option<&'a Term> {
    ts.iter()
        .find(|(s, p, _)| s == subject && p == predicate)
        .map(|(_, _, o)| o)
}

fn as_text(term: &Term) -> String {
    match term {
        Term::NamedNode(n) => n.as_str().to_string(),
        Term::Literal(l) => l.value().to_string(),
        other => other.to_string(),
    }
}

/// Read a verdict atom named `name`.
pub fn parse_verdict(text: &str, name: &str) -> Result<Stored> {
    let ts = triples(text)?;
    let concept = match object(&ts, name, &format!("{OA}hasBody")) {
        Some(Term::NamedNode(n)) => Some(n.as_str().to_string()),
        _ => None,
    };
    let raw = object(&ts, name, &format!("{OA}bodyValue")).map(as_text);
    let created = object(&ts, name, &format!("{DCTERMS}created"))
        .map(as_text)
        .unwrap_or_default();
    let agent = object(&ts, name, &format!("{DCTERMS}creator"))
        .or_else(|| object(&ts, name, &format!("{PROV}wasAssociatedWith")))
        .map(as_text)
        .unwrap_or_default();
    if concept.is_none() && raw.is_none() {
        return Err(Error::Endpoint(format!(
            "the atom for <{name}> has no body"
        )));
    }
    Ok(Stored {
        concept,
        raw,
        created,
        agent,
    })
}

/// Read a last-digest atom: the bare-hex digest.
pub fn parse_last(text: &str, name: &str) -> Result<String> {
    let ts = triples(text)?;
    object(&ts, name, &format!("{DCTERMS}identifier"))
        .map(as_text)
        .and_then(|d| d.strip_prefix("b3:").map(String::from))
        .ok_or_else(|| Error::Endpoint(format!("the atom for <{name}> has no digest")))
}

fn position(ts: &[(String, String, Term)], name: &str) -> Option<u32> {
    object(ts, name, &format!("{SCHEMA}position"))
        .map(as_text)
        .and_then(|n| n.parse().ok())
}

/// Read a reservation atom.
pub fn parse_reservation(text: &str, name: &str) -> Result<Reservation> {
    let ts = triples(text)?;
    let text_of = |p: &str| object(&ts, name, p).map(as_text);
    let cleared = text_of(&format!("{JUDGE}clearedBy")).zip(text_of(&format!("{JUDGE}clearedAt")));
    Ok(Reservation {
        created: text_of(&format!("{DCTERMS}created")).unwrap_or_default(),
        attempt: position(&ts, name).unwrap_or(1),
        cleared,
    })
}

/// Read a failure atom.
pub fn parse_failure(text: &str, name: &str) -> Result<Failure> {
    let ts = triples(text)?;
    let text_of = |p: &str| object(&ts, name, p).map(as_text).unwrap_or_default();
    let failure = Failure {
        attempt: position(&ts, name).unwrap_or(0),
        created: text_of(&format!("{DCTERMS}created")),
        classifier: text_of(&format!("{SCHEMA}identifier")),
        kind: text_of(&format!("{SCHEMA}error")),
        message: text_of(&format!("{SCHEMA}description")),
        charged: text_of(&format!("{JUDGE}charged")),
        retry_at: text_of(&format!("{JUDGE}retryAt")),
    };
    if millis_of(&failure.retry_at).is_none() {
        return Err(Error::Endpoint(format!(
            "the atom for <{name}> has no retry time"
        )));
    }
    Ok(failure)
}

/// Read a spent atom: the count.
pub fn parse_spent(text: &str, name: &str) -> Result<u32> {
    let ts = triples(text)?;
    object(&ts, name, &format!("{SCHEMA}value"))
        .map(as_text)
        .and_then(|n| n.parse().ok())
        .ok_or_else(|| Error::Endpoint(format!("the atom for <{name}> has no count")))
}

/// A Turtle string literal's escapes.
pub fn escape(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if c.is_control() => out.push_str(&format!("\\u{:04X}", c as u32)),
            c => out.push(c),
        }
    }
    out
}

// --- time ---------------------------------------------------------------------------------

/// `(YYYY-MM-DD, YYYY-MM-DDThh:mm:ss.sssZ)` for milliseconds since the epoch (UTC).
pub fn date_time(millis: u64) -> (String, String) {
    let secs = millis / 1000;
    let days = (secs / 86_400) as i64;
    let rem = secs % 86_400;
    // Howard Hinnant's civil_from_days.
    let z = days + 719_468;
    let era = z.div_euclid(146_097);
    let doe = z - era * 146_097;
    let yoe = (doe - doe / 1460 + doe / 36_524 - doe / 146_096) / 365;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let d = doy - (153 * mp + 2) / 5 + 1;
    let m = if mp < 10 { mp + 3 } else { mp - 9 };
    let y = yoe + era * 400 + i64::from(m <= 2);
    let date = format!("{y:04}-{m:02}-{d:02}");
    let time = format!(
        "{date}T{:02}:{:02}:{:02}.{:03}Z",
        rem / 3600,
        rem % 3600 / 60,
        rem % 60,
        millis % 1000
    );
    (date, time)
}

/// Milliseconds since the epoch for a `YYYY-MM-DDThh:mm:ss.sssZ` [`date_time`] wrote.
pub fn millis_of(text: &str) -> Option<u64> {
    let b = text.as_bytes();
    if b.len() != 24 || &text[4..5] != "-" || &text[7..8] != "-" || &text[10..11] != "T" {
        return None;
    }
    if &text[13..14] != ":" || &text[16..17] != ":" || &text[19..20] != "." || &text[23..] != "Z" {
        return None;
    }
    let n = |r: std::ops::Range<usize>| -> Option<i64> {
        let part = &text[r];
        part.bytes()
            .all(|c| c.is_ascii_digit())
            .then(|| part.parse().ok())
            .flatten()
    };
    let (y, m, d) = (n(0..4)?, n(5..7)?, n(8..10)?);
    let (hh, mm, ss, ms) = (n(11..13)?, n(14..16)?, n(17..19)?, n(20..23)?);
    if !(1..=12).contains(&m) || !(1..=31).contains(&d) || hh > 23 || mm > 59 || ss > 59 {
        return None;
    }
    // Howard Hinnant's days_from_civil.
    let y = if m <= 2 { y - 1 } else { y };
    let era = y.div_euclid(400);
    let yoe = y - era * 400;
    let mp = (m + 9) % 12;
    let doy = (153 * mp + 2) / 5 + d - 1;
    let doe = yoe * 365 + yoe / 4 - yoe / 100 + doy;
    let days = era * 146_097 + doe - 719_468;
    let secs = days * 86_400 + hh * 3600 + mm * 60 + ss;
    u64::try_from(secs * 1000 + ms).ok()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn dates() {
        assert_eq!(date_time(0).1, "1970-01-01T00:00:00.000Z");
        // 2026-10-31T10:50:17.123Z
        assert_eq!(date_time(1_793_443_817_123).1, "2026-10-31T10:50:17.123Z");
        assert_eq!(date_time(951_782_400_000).0, "2000-02-29");
        for millis in [0, 951_782_400_000, 1_793_443_817_123, 4_102_444_799_999] {
            assert_eq!(millis_of(&date_time(millis).1), Some(millis));
        }
        assert_eq!(millis_of("2026-10-31"), None);
        assert_eq!(millis_of("2026-13-31T00:00:00.000Z"), None);
    }

    #[test]
    fn reservation_and_failure_atoms_read_back() {
        let r = "urn:file:r";
        let old = format!(
            "{PREFIXES}<{r}> a prov:Activity ;\n  dcterms:subject <urn:v> ;\n  \
             dcterms:created \"2026-10-31T00:00:00.000Z\"^^xsd:dateTime .\n"
        );
        assert_eq!(
            parse_reservation(&old, r).unwrap().attempt,
            1,
            "a PR 4 atom"
        );
        let cleared = reservation_turtle(r, "urn:v", "t", 3, Some(("urn:x:c", "t2")));
        let back = parse_reservation(&cleared, r).unwrap();
        assert_eq!(back.attempt, 3);
        assert_eq!(back.cleared, Some(("urn:x:c".into(), "t2".into())));
        let f = Failure {
            attempt: 2,
            created: "2026-10-31T00:00:00.000Z".into(),
            classifier: "c".into(),
            kind: "timeout".into(),
            message: "said \"no\"\n".into(),
            charged: "unknown".into(),
            retry_at: "2026-10-31T01:00:00.000Z".into(),
        };
        assert_eq!(
            parse_failure(&failure_turtle("urn:f", r, &f), "urn:f").unwrap(),
            f
        );
    }

    #[test]
    fn a_model_atom_reads_back() {
        let name = "urn:iki:judge:model:q:c:d";
        for (concept, raw) in [
            (Some("urn:x:yes"), None),
            (None, Some("I think \"maybe\"\n")),
        ] {
            let text = model_turtle(&ModelRecord {
                name,
                target: "urn:item:1",
                concept,
                raw,
                digest: "d",
                created: "2026-10-31T00:00:00.000Z",
                endpoint: "urn:llm:fake:ask",
                model: "m",
                prompt: "urn:iki:judge:prompt:q",
                prompt_digest: "p",
            });
            let back = parse_verdict(&text, name).unwrap();
            assert_eq!(back.concept.as_deref(), concept);
            assert_eq!(back.raw.as_deref(), raw);
            assert_eq!(back.agent, "urn:llm:fake:ask");
        }
    }

    #[test]
    fn small_atoms_read_back() {
        assert_eq!(parse_spent(&spent_turtle("urn:s", 7), "urn:s").unwrap(), 7);
        assert_eq!(
            parse_last(&last_turtle("urn:l", "urn:i", "ab"), "urn:l").unwrap(),
            "ab"
        );
    }
}
